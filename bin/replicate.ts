#!/usr/bin/env tsx
/**
 * bin/replicate.ts
 *
 * Replica una instancia del agente para un nuevo consultorio.
 *
 * Uso:
 *   pnpm replicate --config=clinica-xyz.json
 *
 * El JSON de configuración incluye:
 *   - nombre del consultorio
 *   - datos del doctor principal
 *   - especialidades activas
 *   - número de WhatsApp
 *   - horarios de atención
 *   - plantillas de mensajes
 *   - configuración del LLM
 */

import { existsSync, mkdirSync, writeFileSync, copyFileSync } from 'fs';
import { resolve, join } from 'path';
import { v7 as uuidv7 } from 'uuid';

interface ClinicConfig {
  clinic: {
    name: string;
    timezone?: string;
    storageDir?: string;
  };
  doctor: {
    name: string;
    lastname: string;
    cedula: number;
    email: string;
    phone: string;
    specialtyId: string;
    dailyLimit: number;
  };
  whatsapp?: {
    enabled: boolean;
    sessionPath?: string;
  };
  businessHours?: {
    startHour: number;
    endHour: number;
    slotMinutes: number;
    workDays: number[]; // 0=Domingo … 6=Sábado
  };
  llm?: {
    provider: 'ollama' | 'anthropic' | 'openai';
    model: string;
    temperature?: number;
    apiKey?: string;
  };
  payments?: {
    provider: 'stripe' | 'mercadopago';
    enabled: boolean;
    apiKey?: string;
    webhookSecret?: string;
  };
}

function parseArgs(): { configPath?: string } {
  const args = process.argv.slice(2);
  const cfg = args.find((a) => a.startsWith('--config='))?.split('=')[1];
  return { configPath: cfg };
}

function loadConfig(path: string): ClinicConfig {
  const abs = resolve(path);
  if (!existsSync(abs)) {
    throw new Error(`Config file not found: ${abs}`);
  }
  // Lazy require para evitar cargar TS en runtime.
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  return require(abs) as ClinicConfig;
}

function generateEnv(cfg: ClinicConfig): string {
  const lines: string[] = [
    `# Auto-generado por replicate.ts - ${new Date().toISOString()}`,
    `NODE_ENV=production`,
    `APP_NAME="${cfg.clinic.name}"`,
    `APP_PORT=3000`,
    `APP_TZ=${cfg.clinic.timezone ?? 'America/Mexico_City'}`,
    `DATABASE_URL=${cfg.clinic.storageDir ? cfg.clinic.storageDir + '/clinic.sqlite' : './storage/clinic.sqlite'}`,
    '',
    `# LLM`,
    `LLM_PROVIDER=${cfg.llm?.provider ?? 'ollama'}`,
    `LLM_MODEL=${cfg.llm?.model ?? 'qwen2.5:7b'}`,
    `LLM_TEMPERATURE=${cfg.llm?.temperature ?? 0.2}`,
  ];
  if (cfg.llm?.provider === 'anthropic') {
    lines.push(`ANTHROPIC_API_KEY=${cfg.llm.apiKey ?? ''}`);
  }
  if (cfg.llm?.provider === 'openai') {
    lines.push(`OPENAI_API_KEY=${cfg.llm.apiKey ?? ''}`);
  }
  lines.push(
    '',
    `# WhatsApp`,
    `WA_ENABLED=${cfg.whatsapp?.enabled ?? false}`,
    `WA_SESSION_PATH=${cfg.whatsapp?.sessionPath ?? './storage/wa-session'}`,
    '',
    `# Pagos`,
    `STRIPE_ENABLED=${cfg.payments?.provider === 'stripe' && cfg.payments.enabled}`,
    `MERCADOPAGO_ENABLED=${cfg.payments?.provider === 'mercadopago' && cfg.payments.enabled}`,
  );
  return lines.join('\n') + '\n';
}

function main(): void {
  const { configPath } = parseArgs();
  if (!configPath) {
    console.error('Usage: pnpm replicate --config=<path-to-json>');
    console.error('Example: pnpm replicate --config=clinica-xyz.json');
    process.exit(1);
  }

  console.log(`[replicate] Loading config from ${configPath}…`);
  const cfg = loadConfig(configPath);

  // 1. Crear directorio de storage
  const storageDir = cfg.clinic.storageDir ?? './storage';
  if (!existsSync(storageDir)) {
    mkdirSync(storageDir, { recursive: true });
    console.log(`[replicate] Created ${storageDir}`);
  }

  // 2. Generar .env
  const envContent = generateEnv(cfg);
  const envPath = resolve('.env');
  if (!existsSync(envPath)) {
    writeFileSync(envPath, envContent);
    console.log(`[replicate] Wrote .env (DOCTOR_NAME, WA_PHONE, LLM_PROVIDER, etc.)`);
  } else {
    console.log(`[replicate] .env already exists, skipping (delete to regenerate)`);
  }

  // 3. Generar seed con doctor y especialidades
  const seedContent = generateSeed(cfg);
  const seedPath = resolve('db/seeds/auto-seed.ts');
  writeFileSync(seedPath, seedContent);
  console.log(`[replicate] Wrote ${seedPath}`);

  // 4. Print instrucciones
  console.log('\n[replicate] ✅ Instance ready. Next steps:');
  console.log('  1. pnpm install');
  console.log('  2. pnpm db:generate');
  console.log('  3. pnpm db:migrate');
  console.log('  4. pnpm db:seed');
  console.log('  5. pnpm start:api     # NestJS API');
  console.log('  6. pnpm start:worker  # Cron + recordatorios');
  console.log('');
  console.log(`[replicate] Clinic ID: ${uuidv7()}`);
  console.log(`[replicate] Doctor: ${cfg.doctor.name} ${cfg.doctor.lastname}`);
}

function generateSeed(cfg: ClinicConfig): string {
  return `// Auto-generated by bin/replicate.ts
import { v7 as uuidv7 } from 'uuid';

export const clinicId = '${uuidv7()}';
export const doctorId = '${uuidv7()}';

export default [
  {
    table: 'doctors',
    values: {
      id: doctorId,
      name: '${cfg.doctor.name}',
      lastname: '${cfg.doctor.lastname}',
      cedula: ${cfg.doctor.cedula},
      email: '${cfg.doctor.email}',
      phone: '${cfg.doctor.phone}',
      specialtyId: '${cfg.doctor.specialtyId}',
      dailyLimit: ${cfg.doctor.dailyLimit},
      active: true,
    },
  },
];
`;
}

main();
